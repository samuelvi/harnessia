from pathlib import Path
import json
import os
import tempfile

from ..effective import EffectiveCoreContext, EffectiveSpace
from ..space import HarnessiaError
from .base import ProjectionPlan
from .native import NativeLink, validate_links_target, write_links


CLAUDE_MARKER = "<!-- Generated by Harnessia from SPACE.md. Do not edit. -->"
CLAUDE_OWNER = "Generated by Harnessia from SPACE.md. Do not edit.\n"
SKILL_MARKER = CLAUDE_OWNER
CORE_PLUGIN_MARKER = "Generated by Harnessia from HARNESSIA.md. Do not edit.\n"
CORE_PLUGIN_NAME = "harnessia-core"


def _present(path: Path) -> bool:
    return path.exists() or path.is_symlink()


def _write_text(target: Path, content: str) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", dir=target.parent, delete=False
        ) as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
            temporary = Path(handle.name)
        os.replace(temporary, target)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()


def render_claude_instructions(space: EffectiveSpace) -> str:
    imports = "\n".join(f"@{path.as_posix()}" for path in space.context_paths)
    return f"{CLAUDE_MARKER}\n{imports}\n"


def render_claude_settings(space: EffectiveSpace) -> dict[str, object]:
    exclusions: list[str] = []
    for name in ("project", "documentation"):
        link = space.definition.directory / name
        if not _present(link):
            continue
        for root in (link.absolute(), link.resolve(strict=True)):
            pattern = f"{root.as_posix()}/**"
            if pattern not in exclusions:
                exclusions.append(pattern)
    return {
        "claudeMdExcludes": exclusions,
        "permissions": {"deny": ["mcp__*"]},
        "sandbox": {
            "enabled": True,
            "autoAllowBashIfSandboxed": False,
            "allowUnsandboxedCommands": False,
            "failIfUnavailable": True,
        },
    }


def build_claude_plan(space: EffectiveSpace) -> ProjectionPlan:
    if space.definition.mcp_servers:
        raise HarnessiaError(
            f"{space.definition.directory / 'SPACE.md'}: Claude projection currently "
            "supports only an empty MCP selection"
        )

    directory = space.definition.directory
    claude_file = directory / "CLAUDE.md"
    claude_directory = directory / ".claude"
    settings = claude_directory / "settings.json"
    mcp = claude_directory / "harnessia-mcp.json"
    skills = claude_directory / "skills"
    owner = claude_directory / ".harnessia-generated"
    instructions_content = render_claude_instructions(space)
    settings_content = json.dumps(render_claude_settings(space), indent=2) + "\n"
    mcp_content = json.dumps({"mcpServers": {}}, indent=2) + "\n"

    def validate() -> None:
        if _present(claude_file):
            if (
                claude_file.is_symlink()
                or not claude_file.is_file()
                or not claude_file.read_text().startswith(CLAUDE_MARKER)
            ):
                raise HarnessiaError(
                    f"{claude_file}: existing CLAUDE.md is not managed by Harnessia; "
                    "move or remove it explicitly"
                )
        if claude_directory.is_symlink():
            raise HarnessiaError(
                f"{claude_directory}: .claude must not be a symbolic link"
            )
        if claude_directory.exists() and not claude_directory.is_dir():
            raise HarnessiaError(f"{claude_directory}: .claude must be a directory")
        owned = (
            owner.is_file()
            and not owner.is_symlink()
            and owner.read_text() == CLAUDE_OWNER
        )
        if _present(owner) and not owned:
            raise HarnessiaError(
                f"{owner}: existing Claude ownership marker is invalid"
            )
        for target in (settings, mcp, skills):
            if _present(target) and not owned:
                raise HarnessiaError(
                    f"{target}: existing Claude asset is not managed by Harnessia; "
                    "move or remove it explicitly"
                )
        validate_links_target(skills, SKILL_MARKER, "Claude skill")

    def write() -> None:
        _write_text(claude_file, instructions_content)
        _write_text(settings, settings_content)
        _write_text(mcp, mcp_content)
        write_links(
            skills,
            (
                NativeLink(skill.id, skill.directory)
                for skill in space.skills.skills
            ),
            SKILL_MARKER,
            "claude-skills",
        )
        _write_text(owner, CLAUDE_OWNER)

    return ProjectionPlan(
        client="claude",
        targets=(claude_file, settings, mcp, skills, owner),
        validate=validate,
        write=write,
    )


def _write_core_plugin(target: Path, skills: tuple[NativeLink, ...]) -> None:
    if not skills:
        return
    if target.parent.is_symlink():
        raise HarnessiaError(
            f"{target.parent}: projection parent must not be a symbolic link"
        )
    target.mkdir(parents=True)
    (target / ".harnessia-generated").write_text(CORE_PLUGIN_MARKER)
    plugin_root = target / CORE_PLUGIN_NAME
    manifest = plugin_root / ".claude-plugin/plugin.json"
    skill_directory = plugin_root / "skills"
    manifest.parent.mkdir(parents=True)
    skill_directory.mkdir()
    manifest.write_text(
        json.dumps(
            {
                "name": CORE_PLUGIN_NAME,
                "version": "1.0.0",
                "description": "Core skills selected by Harnessia.",
                "skills": [f"./skills/{skill.name}" for skill in skills],
            },
            indent=2,
        )
        + "\n"
    )
    for skill in skills:
        link = skill_directory / skill.name
        link.symlink_to(Path(os.path.relpath(skill.target, skill_directory)))


def build_core_claude_plan(context: EffectiveCoreContext) -> ProjectionPlan:
    target = context.definition.directory / ".claude/skills"
    skills = tuple(
        NativeLink(skill.id, skill.directory) for skill in context.skills.skills
    )

    def validate() -> None:
        validate_links_target(target, CORE_PLUGIN_MARKER, "Core Claude plugin")

    def write() -> None:
        _write_core_plugin(target, skills)

    return ProjectionPlan(
        client="Core Claude",
        targets=(target,),
        validate=validate,
        write=write,
    )
