from pathlib import Path
import json
import os
import tempfile

from ..effective import EffectiveCoreContext, EffectiveSpace
from ..space import HarnessiaError
from .base import ProjectionPlan
from .native import (
    CORE_SKILL_MARKER,
    NativeLink,
    validate_agent_target,
    validate_command_target,
    write_agents,
    write_commands,
    validate_links_target,
    write_links,
)


GENERATED_MARKER = "// Generated by Harnessia from SPACE.md. Do not edit."


def _relative(path: Path, directory: Path) -> str:
    return Path(os.path.relpath(path, directory)).as_posix()


def render_opencode(
    space: EffectiveSpace,
) -> dict[str, object]:
    permissions: list[dict[str, str]] = [
        {"action": "skill", "resource": "*", "effect": "deny"}
    ]
    permissions.extend(
        {"action": "skill", "resource": skill_id, "effect": "allow"}
        for skill_id in space.skills.ids
    )
    policies: list[dict[str, str]] = [
        {"action": "integration.use", "resource": "mcp:*", "effect": "deny"}
    ]
    policies.extend(
        {
            "action": "integration.use",
            "resource": f"mcp:{server_id}",
            "effect": "allow",
        }
        for server_id in space.definition.mcp_servers
    )
    return {
        "$schema": "https://opencode.ai/config.json",
        "instructions": [path.as_posix() for path in space.context_paths],
        "skills": [
            _relative(catalog, space.definition.directory)
            for catalog in space.skills.catalog_roots
        ],
        "permissions": permissions,
        "policies": policies,
    }


def validate_projection_target(target: Path) -> None:
    if target.exists() and not target.read_text().startswith(GENERATED_MARKER):
        raise HarnessiaError(
            f"{target}: existing opencode.jsonc is not managed by Harnessia; "
            "move or remove it explicitly"
        )


def write_projection(target: Path, config: dict[str, object]) -> None:
    validate_projection_target(target)
    content = GENERATED_MARKER + "\n" + json.dumps(config, indent=2) + "\n"
    target.parent.mkdir(parents=True, exist_ok=True)
    temporary: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", dir=target.parent, delete=False
        ) as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
            temporary = Path(handle.name)
        os.replace(temporary, target)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()


def build_opencode_plan(space: EffectiveSpace) -> ProjectionPlan:
    directory = space.definition.directory
    projection = directory / "opencode.jsonc"
    agents = directory / ".opencode/agents"
    commands = directory / ".opencode/commands"
    config = render_opencode(space)

    def validate() -> None:
        validate_projection_target(projection)
        validate_agent_target(agents)
        validate_command_target(commands)

    def write() -> None:
        write_projection(projection, config)
        write_agents(agents, space.agents)
        write_commands(commands, space.commands)

    return ProjectionPlan(
        client="opencode",
        targets=(projection, agents, commands),
        validate=validate,
        write=write,
    )


def build_core_opencode_plan(context: EffectiveCoreContext) -> ProjectionPlan:
    target = context.definition.directory / ".opencode/skills"

    def validate() -> None:
        validate_links_target(target, CORE_SKILL_MARKER, "Core OpenCode skill")

    def write() -> None:
        write_links(
            target,
            (NativeLink(skill.id, skill.directory) for skill in context.skills.skills),
            CORE_SKILL_MARKER,
            "core-opencode-skills",
        )

    return ProjectionPlan(
        client="Core OpenCode",
        targets=(target,),
        validate=validate,
        write=write,
    )
