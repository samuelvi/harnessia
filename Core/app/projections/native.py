from pathlib import Path
from dataclasses import dataclass
from typing import Iterable
import os
import shutil
import tempfile
from uuid import uuid4

from ..capabilities.agents import AgentInventory
from ..capabilities.commands import CommandInventory
from ..space import HarnessiaError


MARKER_NAME = ".harnessia-generated"
AGENT_MARKER = "Generated by Harnessia from SPACE.md. Do not edit.\n"
COMMAND_MARKER = "Generated by Harnessia from SPACE.md. Do not edit.\n"
CORE_SKILL_MARKER = "Generated by Harnessia from HARNESSIA.md. Do not edit.\n"


@dataclass(frozen=True)
class NativeLink:
    name: str
    target: Path


def _is_owned(target: Path, marker_text: str) -> bool:
    marker = target / MARKER_NAME
    return (
        target.is_dir()
        and not target.is_symlink()
        and marker.is_file()
        and marker.read_text() == marker_text
    )


def validate_links_target(target: Path, marker_text: str, label: str) -> None:
    if (target.exists() or target.is_symlink()) and not _is_owned(target, marker_text):
        raise HarnessiaError(
            f"{target}: existing {label} directory is not managed by Harnessia; "
            "move or remove it explicitly"
        )


def write_links(
    target: Path,
    links: Iterable[NativeLink],
    marker_text: str,
    label: str,
) -> None:
    parent = target.parent
    if parent.is_symlink():
        raise HarnessiaError(f"{parent}: projection parent must not be a symbolic link")
    parent.mkdir(parents=True, exist_ok=True)
    validate_links_target(target, marker_text, label)
    links = tuple(links)

    staged: Path | None = None
    backup: Path | None = None
    try:
        if links:
            staged = Path(tempfile.mkdtemp(prefix=f".{label}-stage-", dir=parent))
            (staged / MARKER_NAME).write_text(marker_text)
            for native_link in links:
                if Path(native_link.name).name != native_link.name:
                    raise HarnessiaError(
                        f"{native_link.name}: native link name must be a filename"
                    )
                link = staged / native_link.name
                link.symlink_to(Path(os.path.relpath(native_link.target, staged)))

        if target.exists():
            backup = parent / f".{label}-backup-{uuid4().hex}"
            os.replace(target, backup)
        if staged is not None:
            os.replace(staged, target)
            staged = None
        if backup is not None:
            shutil.rmtree(backup)
            backup = None
    except OSError:
        if target.exists() and backup is not None:
            shutil.rmtree(target)
        if backup is not None and backup.exists():
            os.replace(backup, target)
            backup = None
        raise
    finally:
        if staged is not None and staged.exists():
            shutil.rmtree(staged)
        if backup is not None and backup.exists():
            shutil.rmtree(backup)


def validate_agent_target(target: Path) -> None:
    validate_links_target(target, AGENT_MARKER, "agent")


def write_agents(target: Path, inventory: AgentInventory) -> None:
    write_links(
        target,
        (NativeLink(f"{agent.id}.md", agent.path) for agent in inventory.agents),
        AGENT_MARKER,
        "agents",
    )


def validate_command_target(target: Path) -> None:
    validate_links_target(target, COMMAND_MARKER, "command")


def write_commands(target: Path, inventory: CommandInventory) -> None:
    write_links(
        target,
        (
            NativeLink(f"{command.id}.md", command.path)
            for command in inventory.commands
        ),
        COMMAND_MARKER,
        "commands",
    )
